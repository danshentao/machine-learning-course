import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import fs from 'node:fs';
const require=createRequire('E:/机器学习课设/第二代鸟类检测与细粒度分类/work/html_review/check.mjs');
const {chromium}=require('playwright');
const base='E:/机器学习课设/第三代鸟类识别现代模型对照';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1500,height:1100}});const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto(pathToFileURL(base+'/reports/第三代对照/第三代分类模型逐图对照.html').href);
await page.waitForFunction(()=>document.querySelector('canvas')?.width>300);
const first=await page.locator('#count').innerText();
await page.selectOption('#filter','all');const all=await page.locator('#count').innerText();
if(!all.includes('172'))throw new Error('172 images absent');
await page.fill('#search','shanmaque_104');await page.locator('#gt').check();await page.waitForTimeout(400);
if(await page.locator('article').count()!==1)throw new Error('Search failed');
await page.screenshot({path:base+'/reports/第三代对照/页面检查.png',fullPage:true});
if(errors.length)throw new Error(errors.join('\n'));
fs.writeFileSync(base+'/reports/第三代对照/页面检查.json',JSON.stringify({first,all,search:'shanmaque_104',page_errors:errors},null,2));
console.log(JSON.stringify({first,all,page_errors:errors}));await browser.close();
